// The zone PACKAGE folders are the ONE source of truth for a package's rows (docs/specs/zone-package.md, step 2; Lead 2026-10-18): origins/packages/<id>/ holds the zone row, its dungeon and theme rows, the exits and warps it
// owns and the manifest. The shared tables a zone's rows live in (exit-rows.json, dungeon-rows.json, dungeon-themes.json) and the zone row files (origins/zone-rows/zone<N>.row.json of a package) are BUILD OUTPUT of this
// script, the gen-zones way: `npm run packages` writes them, tests/package-registry.test.ts fails when a committed one differs from a fresh generation (a hand edit), and the vite build runs it first.
// The same `validatePackage` is the import tool's gate (Strategy's rules): every bound is a row (origins/zones/package-rules.json, named and counted), the manifest hash check is mandatory, a NEW package imports
// unlisted, a replace is explicit per id, and a path outside the package folder, an asset outside public/ or a remote URL is refused. Pure over its inputs; the CLI is at the bottom.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
export const canon = (v) => `${JSON.stringify(v, null, 2)}\n`;
const sha = (s) => createHash('sha256').update(s).digest('hex');
export const SCHEMA = 1;
export const FILES = ['zone.row.json', 'dungeon.row.json', 'theme.row.json', 'exits.json', 'warps.json'];   // the only names a package folder may hold, besides package.json
export const NAMED_RULES = ['maxFiles', 'maxFileBytes', 'maxExits', 'maxWarps', 'maxCreatures', 'maxRooms'];
const EXIT_FIELDS = { id: 'string', zone: 'string', landmark: 'string', to: 'string', arrive: 'string', warp: 'string', radiusM: 'number', arriveM: 'number', label: 'string' };
const WARP_FIELDS = { id: 'string', x: 'number', z: 'number', unit: 'string' };
const GENERATED = 'GENERATED by scripts/gen-packages.mjs from origins/packages/<id>/: do not edit (npm run packages)';

/** The bounds, from the rows file: every NAMED rule must be a row with a positive number, and no other id may hide in the file. */
export function loadRules(raw = JSON.parse(readFileSync(join(ROOT, 'origins/zones/package-rules.json'), 'utf8'))) {
  const rows = raw.rules ?? [], out = {};
  for (const r of rows) { if (!NAMED_RULES.includes(r.id)) throw new Error(`package-rules: "${r.id}" is not a named rule`); if (!(Number.isFinite(r.value) && r.value > 0)) throw new Error(`package-rules "${r.id}": value is a number > 0`); if (r.id in out) throw new Error(`package-rules: "${r.id}" twice`); out[r.id] = r.value; }
  for (const n of NAMED_RULES) if (!(n in out)) throw new Error(`package-rules: the importer reads the "${n}" rule by name, so it needs a row`);
  return out;
}

const fieldsProblems = (row, fields, what) => Object.entries(fields).flatMap(([k, t]) => (typeof row?.[k] === t && (t !== 'number' || Number.isFinite(row[k])) ? [] : [`${what}: field "${k}" must be a ${t}`]));
const LOCAL_ASSET = /^\/(world|arena)\/[A-Za-z0-9._\-/]+$/;
const urlsIn = (v, out = []) => { if (v && typeof v === 'object') for (const [k, x] of Object.entries(v)) { if (k === 'url' && typeof x === 'string') out.push(x); else urlsIn(x, out); } return out; };

/** Everything wrong with one package's files. `files` is { name: text } including package.json; `ctx` says what already exists:
 *  { rules, mode: 'import' | 'generate', existing: { zones: Set<string>, exits, dungeons, themes, warps: Set<string> }, replace: Set<string>, publicHas(path): boolean }.
 *  In `generate` mode `existing` is the OTHER packages (a clash between two packages); in `import` mode it is everything already in the repo. */
export function validatePackage(files, ctx) {
  const bad = [], R = ctx.rules;
  let m; try { m = JSON.parse(files['package.json'] ?? ''); } catch { return ['package.json is missing or not JSON']; }
  if (m.schema !== SCHEMA) bad.push(`manifest schema must be ${SCHEMA}`);
  if (typeof m.id !== 'string' || !/^[a-z0-9][a-z0-9-]*$/.test(m.id)) bad.push('manifest id must be lowercase letters, digits and dashes');
  if (!Number.isInteger(m.zone) || m.zone < 1) bad.push('manifest zone must be a whole number from 1');
  // 1. paths: only the known names, plain (no folder, no .., no absolute), and not more than the bound
  const names = Object.keys(files).filter((f) => f !== 'package.json');
  for (const f of [...names, ...Object.keys(m.files ?? {})]) if (!FILES.includes(f)) bad.push(`file "${f}" is not an allowed package file name (${FILES.join(', ')}); a path is never accepted`);
  if (names.length > R.maxFiles) bad.push(`${names.length} files is over the bound of ${R.maxFiles}`);
  // 2. the hash check is mandatory: every listed file present and exact, every present file listed
  for (const [f, h] of Object.entries(m.files ?? {})) {
    if (!(f in files)) bad.push(`manifest lists "${f}" but it is not in the package`);
    else if (sha(files[f]) !== h?.sha256 || Buffer.byteLength(files[f]) !== h?.bytes) bad.push(`"${f}" does not match its manifest hash`);
  }
  for (const f of names) { if (!(f in (m.files ?? {}))) bad.push(`"${f}" is in the package but not in the manifest`); if (Buffer.byteLength(files[f]) > R.maxFileBytes) bad.push(`"${f}" is over the bound of ${R.maxFileBytes} bytes`); }
  const rows = {}; for (const f of names) { try { rows[f] = JSON.parse(files[f]); } catch { bad.push(`"${f}" is not JSON`); } }
  const zone = rows['zone.row.json'], dungeon = rows['dungeon.row.json'], theme = rows['theme.row.json'], ex = rows['exits.json'] ?? { owned: [], inbound: [] }, warps = rows['warps.json'] ?? [];
  if (!zone) bad.push('a package needs its zone.row.json');
  // 3. rows have their shapes and bounds, and the manifest's `owns` says what the files hold
  const exitRows = [...(ex.owned ?? []), ...(ex.inbound ?? [])];
  if ((ex.owned ?? []).length + (ex.inbound ?? []).length > R.maxExits) bad.push(`more than ${R.maxExits} exit rows`);
  if (warps.length > R.maxWarps) bad.push(`more than ${R.maxWarps} warp rows`);
  if ((dungeon?.creatures ?? []).length > R.maxCreatures) bad.push(`more than ${R.maxCreatures} creature rows`);
  if ((dungeon?.rooms ?? []).length > R.maxRooms) bad.push(`more than ${R.maxRooms} rooms`);
  for (const e of exitRows) bad.push(...fieldsProblems(e, EXIT_FIELDS, `exit "${e?.id}"`));
  for (const w of warps) bad.push(...fieldsProblems(w, WARP_FIELDS, `warp "${w?.id}"`));
  const world = new Set(m.world ?? []);
  for (const e of ex.owned ?? []) if (!world.has(e.zone)) bad.push(`owned exit "${e.id}" stands in "${e.zone}", which is not a world zone of the package`);
  for (const e of ex.inbound ?? []) { if (e.to !== String(m.zone)) bad.push(`inbound exit "${e.id}" goes to "${e.to}", not to this zone (${m.zone})`); if (world.has(e.zone)) bad.push(`inbound exit "${e.id}" stands inside the package`); }
  const same = (a, b) => JSON.stringify([...a].sort()) === JSON.stringify([...b].sort());
  if (!same(m.owns?.exits ?? [], (ex.owned ?? []).map((e) => e.id))) bad.push('manifest owns.exits does not match exits.json');
  if (!same(m.inbound?.exits ?? [], (ex.inbound ?? []).map((e) => e.id))) bad.push('manifest inbound.exits does not match exits.json');
  if ((m.owns?.dungeon ?? null) !== (dungeon?.id ?? null)) bad.push('manifest owns.dungeon does not match dungeon.row.json');
  if ((m.owns?.theme ?? null) !== (theme?.id ?? null)) bad.push('manifest owns.theme does not match theme.row.json');
  if (!same(m.owns?.warps ?? [], warps.map((w) => w.id))) bad.push('manifest owns.warps does not match warps.json');
  // 4. assets: a local path under public/ (/world/ or /arena/) that exists; never a remote url, a scheme, a .. or a protocol-relative url
  for (const u of [...new Set([...urlsIn(zone), ...urlsIn(theme), ...(m.uses?.kit ?? [])])]) {
    if (!LOCAL_ASSET.test(u) || u.includes('..') || u.includes('//')) bad.push(`asset "${u}" is not a local path under /world/ or /arena/`);
    else if (!ctx.publicHas(u)) bad.push(`asset "${u}" is not a file under public/`);
  }
  // 5. clashes and the unlisted default
  const clash = (kind, id, set) => { if (set?.has(id) && !ctx.replace.has(id)) bad.push(`${kind} "${id}" already exists: name it in --replace to replace it`); };
  clash('zone', String(m.zone), ctx.existing.zones);
  if (dungeon) clash('dungeon', dungeon.id, ctx.existing.dungeons);
  if (theme) clash('theme', theme.id, ctx.existing.themes);
  for (const e of ex.owned ?? []) clash('exit', e.id, ctx.existing.exits);
  for (const e of ex.inbound ?? []) clash('exit', e.id, ctx.existing.exits);
  for (const w of warps) clash('warp', w.id, ctx.existing.warps);
  if (ctx.mode === 'import' && !ctx.existing.zones.has(String(m.zone)) && (zone?.unlisted !== true || m.unlisted !== true)) bad.push('a new package imports unlisted: zone.row.json and the manifest must say "unlisted": true');
  return bad;
}

const readFolder = (dir) => Object.fromEntries(readdirSync(dir).map((f) => [f, readFileSync(join(dir, f), 'utf8')]));
export const PACKAGES = (root = ROOT) => join(root, 'origins/packages');
export function readPackages(root = ROOT) {
  const dir = PACKAGES(root);
  return existsSync(dir) ? readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort().map((id) => ({ id, files: readFolder(join(dir, id)) })) : [];
}

/** Everything the packages generate: { relative path: text }. Throws on any package problem or a clash between two packages. */
export function generate(root = ROOT) {
  const pkgs = readPackages(root), rules = loadRules(JSON.parse(readFileSync(join(root, 'origins/zones/package-rules.json'), 'utf8')));
  const out = {}, tables = { exits: [], dungeons: [], themes: [] }, zones = [], seen = { zones: new Set(), exits: new Set(), dungeons: new Set(), themes: new Set(), warps: new Set() };
  for (const p of pkgs) {
    const bad = validatePackage(p.files, { rules, mode: 'generate', existing: seen, replace: new Set(), publicHas: (u) => existsSync(join(root, 'public', u)) });
    if (bad.length) throw new Error(`package "${p.id}": ${bad.join('; ')}`);
    const m = JSON.parse(p.files['package.json']), ex = JSON.parse(p.files['exits.json'] ?? '{"owned":[],"inbound":[]}');
    if (m.id !== p.id) throw new Error(`package folder "${p.id}" holds the manifest of "${m.id}"`);
    seen.zones.add(String(m.zone)); out[`origins/zone-rows/zone${m.zone}.row.json`] = p.files['zone.row.json'];
    for (const e of [...ex.inbound, ...ex.owned]) { tables.exits.push(e); seen.exits.add(e.id); }   // the door in from the far zone first, then the door out: the order the shared table has always had (the unlisted-crypt test pins it)
    if (p.files['dungeon.row.json']) { const d = JSON.parse(p.files['dungeon.row.json']); tables.dungeons.push(d); seen.dungeons.add(d.id); }
    if (p.files['theme.row.json']) { const t = JSON.parse(p.files['theme.row.json']); tables.themes.push(t); seen.themes.add(t.id); }
    zones.push(m.zone);
  }
  for (const d of tables.dungeons) if (!seen.themes.has(d.theme)) throw new Error(`dungeon "${d.id}" uses theme "${d.theme}", which no package carries`);
  out['origins/zones/exit-rows.json'] = canon({ generated: GENERATED, exits: tables.exits });
  out['origins/zones/dungeon-rows.json'] = canon({ generated: GENERATED, dungeons: tables.dungeons });
  out['origins/zones/dungeon-themes.json'] = canon({ generated: GENERATED, themes: tables.themes });
  return out;
}
export const writeGenerated = (root = ROOT) => { const out = generate(root); for (const [f, t] of Object.entries(out)) { mkdirSync(join(root, f, '..'), { recursive: true }); writeFileSync(join(root, f), t); } return Object.keys(out); };

if (process.argv[1] === fileURLToPath(import.meta.url)) { for (const f of writeGenerated()) console.log(`wrote ${f}`); }
