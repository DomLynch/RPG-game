// Writes origins/zones/registry.ts: one JSON import per zone row (origins/zone-rows/zone<N>.row.json), so adding a zone is adding its row and nothing else (Dom 2026-10-09 plug and play; 2026-10-11 the row IS the zone,
// no generated TypeScript per zone). `node scripts/gen-zones.mjs` rewrites it; the vite build runs it first; tests/zone-registry.test.ts fails if the committed file is stale.
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const ZONES_DIR = fileURLToPath(new URL('../origins/zones/', import.meta.url));
export const ROWS_DIR = fileURLToPath(new URL('../origins/zone-rows/', import.meta.url));

// The zone rows under `dir` (zone1.row.json, zone2.row.json, ... zone99), by number. A file that is not named zone<N>.row.json (a leading zero, a stray name) is an error, never skipped.
export function zoneRows(dir = ROWS_DIR) {
  return readdirSync(dir).filter((f) => f.endsWith('.row.json')).map((file) => {
    const m = /^zone([1-9][0-9]*)\.row\.json$/.exec(file);
    if (!m) throw new Error(`${file} is not a zone row name (zone<N>.row.json, N a number without a leading zero)`);
    return { file, id: m[1], n: Number(m[1]) };
  }).sort((a, b) => a.n - b.n);
}
export function registrySource(dir = ROWS_DIR) {
  const rows = zoneRows(dir), lines = ['// GENERATED by scripts/gen-zones.mjs from origins/zone-rows/zone<N>.row.json: do not edit (npm run zones).', "import { zoneFromRow } from './from-row.ts';"];
  for (const r of rows) lines.push(`import row${r.id} from '../zone-rows/${r.file}' with { type: 'json' };`);
  lines.push('', 'export const REGISTRY = {');
  for (const r of rows) lines.push(`  '${r.id}': zoneFromRow(${r.n}, row${r.id}),`);
  lines.push('};', '');
  return lines.join('\n');
}
if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(`${ZONES_DIR}registry.ts`, registrySource());
