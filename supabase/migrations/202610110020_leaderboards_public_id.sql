begin;
-- Core slice 2c: the boards stop showing display names (no name filter yet) and show a stable PUBLIC fighter number instead.
--  * fighter_profiles.public_no: identity integer, unique, never reused, not client-writable (the insert/update grants are per column and do not name it). It is not derived from the auth uid.
--  * leaderboards() keeps board, place, display_name, score and adds fighter_id. display_name now carries 'Fighter #<public_no>' so the client needs no change; when a name filter is live a later migration swaps that expression back to the name. Ties break on public_no.
alter table public.fighter_profiles add column public_no integer generated by default as identity unique;
drop function public.leaderboards(integer);
create function public.leaderboards(p_limit integer default 20) returns table (board text, place integer, display_name text, score integer, fighter_id integer)
language sql stable security definer set search_path = '' as $$
  with lim as (select greatest(1, least(coalesce(p_limit, 20), 50)) n),
  a as (select 'duel_rating'::text board, row_number() over (order by d.rating desc, p.public_no)::integer place, p.public_no, d.rating score
        from public.duel_ratings d join public.fighter_profiles p on p.user_id = d.user_id),
  b as (select 'duel_wins'::text board, row_number() over (order by w.n desc, p.public_no)::integer place, p.public_no, w.n::integer score
        from (select user_id, count(*) n from public.fight_results where kind = 'duel' and result = 'win' group by user_id) w join public.fighter_profiles p on p.user_id = w.user_id)
  select a.board, a.place, 'Fighter #' || a.public_no, a.score, a.public_no from a, lim where a.place <= lim.n
  union all select b.board, b.place, 'Fighter #' || b.public_no, b.score, b.public_no from b, lim where b.place <= lim.n
  order by 1, 2
$$;
revoke all on function public.leaderboards(integer) from public, anon;
grant execute on function public.leaderboards(integer) to authenticated;
commit;
